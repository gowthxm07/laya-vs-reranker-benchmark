import { Chunk } from "./chunk";
import { CandidateChunkPool } from "./candidate-pool";
import { TraceEvent } from "./trace";
import { GenerationOptions } from "../interfaces/llm-provider";

/**
 * Operating comparison mode:
 * - "native": Cross-Encoder selects Top-N, Laya retains all KEEP candidates
 * - "context-budget": Both paths are constrained by maxContextChunks limit
 */
export type ComparisonMode = "native" | "context-budget";

/**
 * Options passed to the comparison orchestrator
 */
export interface ComparisonOptions {
  /** Mode of comparison */
  mode?: ComparisonMode;

  /** Number of chunks for Cross-Encoder top-N selection (default: 5) */
  topN?: number;

  /** Maximum context chunks allowed when mode is "context-budget" (default: 5) */
  maxContextChunks?: number;

  /** LLM generation options (temperature, seed, maxTokens, etc.) */
  generationOptions?: GenerationOptions;
}

/**
 * Detailed result of a single pipeline path (Path A or Path B) within the comparison
 */
export interface PathComparisonResult {
  /** Pipeline identifier */
  pipelineId: "advanced-rag" | "laya-rag";

  /** Strategy name (e.g. "Cross-Encoder (ms-marco-MiniLM-L-6-v2)" or "Laya Relevance Filter (ModernBERT)") */
  strategyName: string;

  /** Strategy identifier */
  strategyId: string;

  /** IDs of the chunks selected for final prompt context */
  selectedChunkIds: string[];

  /** Full chunk objects selected for prompt context */
  selectedChunks: Chunk[];

  /** Number of chunks retained */
  retainedCount: number;

  /** Number of chunks discarded */
  discardedCount: number;

  /** Assembled context text passed to LLM */
  contextText: string;

  /** Character length of assembled context text */
  contextCharacterCount: number;

  /** Token count of assembled context text */
  contextTokenCount: number;

  /** Whether the token count was estimated or reported directly by the provider */
  isTokenCountEstimated: boolean;

  /** Latency of post-retrieval relevance evaluation/filtering (ms) */
  relevanceLatencyMs: number;

  /** Latency of context construction (ms) */
  contextBuildLatencyMs: number;

  /** Latency of downstream LLM generation (ms) */
  generationLatencyMs: number;

  /** Total latency for this path (relevance + context + generation) (ms) */
  totalLatencyMs: number;

  /** Generated answer text from downstream LLM */
  answer: string;

  /** Prompt tokens reported by LLM provider */
  promptTokens: number;

  /** Completion tokens generated by LLM */
  completionTokens: number;

  /** Total tokens consumed by LLM call */
  totalTokens: number;

  /** Error message if this branch failed */
  error?: string;

  /** Additional diagnostic metadata */
  metadata?: Record<string, unknown>;
}

/**
 * Structured result of an end-to-end head-to-head comparison
 */
export interface ComparisonResult {
  /** Unique benchmark comparison run identifier */
  id: string;

  /** Natural language user query */
  query: string;

  /** Epoch millisecond timestamp of run */
  timestamp: number;

  /** Active comparison mode */
  mode: ComparisonMode;

  /** Configured Top-N parameter */
  topN: number;

  /** Configured maximum context chunks parameter (if context-budget mode) */
  maxContextChunks?: number;

  /** Shared retrieval stage details (experimental control) */
  sharedRetrieval: {
    candidateCount: number;
    retrievalLatencyMs: number;
    candidatePool: CandidateChunkPool;
  };

  /** Path A result: Advanced RAG with Cross-Encoder */
  crossEncoder: PathComparisonResult;

  /** Path B result: Laya RAG with Relevance Evaluator */
  laya: PathComparisonResult;

  /** Overall wall-clock comparison latency (ms) */
  overallLatencyMs: number;

  /** Full end-to-end trace events captured by Observer */
  trace: TraceEvent[];

  /** Downstream LLM model identifier */
  llmModel: string;

  /** Downstream LLM provider identifier */
  llmProvider: string;

  /** Downstream LLM generation options used */
  generationParameters: GenerationOptions;
}
