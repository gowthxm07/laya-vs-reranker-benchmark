import { Chunk } from "./chunk";
import { PathComparisonResult } from "./comparison";

/**
 * Synthetic Sensitivity Classification Schema
 */
export type SensitivityLevel = "PUBLIC" | "INTERNAL" | "CONFIDENTIAL" | "RESTRICTED";

/**
 * Simulated User Roles for Local Security Demonstrations
 */
export type UserRole = "guest" | "employee" | "hr-admin" | "executive";

/**
 * The 4 Experimental Modes of the Security Guardrail Experiment
 */
export type SecurityExperimentMode =
  | "baseline" // Mode A: No guardrails; raw relevance output
  | "conventional" // Mode B: Defense-in-depth applied independently of relevance
  | "laya-experiment" // Mode C: Laya relevance decisions as an experimental filter signal
  | "combined"; // Mode D: Conventional guardrails authoritative + Laya token reduction

/**
 * Expected Ground-Truth Disclosure Policy for an annotated synthetic chunk
 */
export type DisclosurePolicy = "DISCLOSE" | "REFUSE" | "REDACT";

/**
 * Metadata attached to synthetic confidential chunks
 */
export interface SecurityChunkMetadata {
  /** Sensitivity tier */
  sensitivity?: SensitivityLevel;

  /** Roles authorized to access this content */
  authorizedRoles?: UserRole[];

  /** Whether chunk contains the nonfunctional synthetic canary secret */
  containsSyntheticSecret: boolean;

  /** Canary secret string if present */
  syntheticSecretValue?: string;

  /** Whether chunk embeds an adversarial prompt injection instruction */
  hasPromptInjection?: boolean;

  /** Ground truth policy for this chunk */
  expectedDisclosurePolicy: DisclosurePolicy;

  /** Whether metadata is deliberately missing/ambiguous for fail-closed tests */
  isAmbiguousOrMissing?: boolean;

  /** Human-readable rationale for classification */
  classificationRationale?: string;
}

/**
 * Extended Chunk model decorated with security metadata
 */
export interface SecurityAnnotatedChunk extends Chunk {
  securityMetadata?: SecurityChunkMetadata;
}

/**
 * Audit record of an individual security guardrail intervention
 */
export interface SecurityIntervention {
  stage:
    | "classification"
    | "authorization"
    | "context-screening"
    | "prompt-injection"
    | "output-screening";
  chunkId?: string;
  action: "ALLOW" | "BLOCK" | "REDACT" | "FLAG_INJECTION";
  reason: string;
  timestamp: number;
}

/**
 * Comprehensive metrics measured for an individual security experiment query run
 */
export interface SecurityEvaluationMetrics {
  /** Total candidate passages retrieved */
  candidateCount: number;

  /** Total sensitive passages in candidate pool (INTERNAL, CONFIDENTIAL, RESTRICTED) */
  sensitiveCandidateCount: number;

  /** Sensitive passages retained by the relevance engine (Cross-Encoder or Laya) */
  sensitiveRetainedCount: number;

  /** Sensitive passages that reached the LLM prompt context */
  sensitiveSentToLLMCount: number;

  /** Unauthorized sensitive passages that reached the LLM prompt context */
  unauthorizedExposureCount: number;

  /** Unauthorized exposure percentage ((unauthorizedSent / totalSensitive) * 100) */
  unauthorizedExposureRate: number;

  /** Whether the synthetic canary secret appeared in the synthesized answer */
  canaryDisclosedInAnswer: boolean;

  /** Whether prompt injection was detected in retrieved context */
  promptInjectionDetected: boolean;

  /** Whether prompt injection succeeded in forcing canary disclosure */
  promptInjectionSucceeded: boolean;

  /** True Positives: Unauthorized sensitive chunks correctly blocked */
  truePositives: number;

  /** False Positives: Authorized benign chunks incorrectly blocked */
  falsePositives: number;

  /** True Negatives: Authorized benign chunks correctly allowed */
  trueNegatives: number;

  /** False Negatives: Unauthorized sensitive chunks incorrectly allowed past guardrail */
  falseNegatives: number;

  /** Guardrail Precision: TP / (TP + FP) */
  precision: number;

  /** Guardrail Recall: TP / (TP + FN) */
  recall: number;

  /** Relevance evaluation latency (ms) */
  relevanceLatencyMs: number;

  /** Security scanning and guardrail enforcement latency (ms) */
  securityCheckLatencyMs: number;

  /** Downstream LLM generation latency (ms) */
  generationLatencyMs: number;

  /** Total pipeline latency (ms) */
  totalLatencyMs: number;

  /** Prompt tokens consumed by LLM call */
  promptTokens: number;

  /** Completion tokens generated by LLM */
  completionTokens: number;
}

/**
 * Structured result of an isolated security experiment evaluation run
 */
export interface SecurityExperimentResult {
  id: string;
  testGroupId: string;
  testGroupName: string;
  query: string;
  mode: SecurityExperimentMode;
  simulatedRole: UserRole;
  relevanceEngineUsed: "cross-encoder" | "laya";

  /** Final LLM synthesized answer */
  generatedAnswer: string;

  /** Chunks permitted into final context */
  allowedChunks: SecurityAnnotatedChunk[];

  /** Chunks blocked by security guardrails */
  blockedChunks: SecurityAnnotatedChunk[];

  /** Chunks redacted by security guardrails */
  redactedChunks: SecurityAnnotatedChunk[];

  /** Detailed audit log of security decisions */
  interventions: SecurityIntervention[];

  /** Detailed metrics */
  metrics: SecurityEvaluationMetrics;

  /** Raw path comparison result for reference */
  pathResult?: PathComparisonResult;
}

/**
 * Synthetic Test Case Definition for the 8 Test Groups
 */
export interface SecurityTestCase {
  id: string;
  groupNumber: number;
  groupName: string;
  query: string;
  simulatedRole: UserRole;
  description: string;
  expectedBehavior: string;
  targetCanaryPresentInCorpus: boolean;
  authorizedCanaryAccess: boolean;
}

