import { Chunk } from "./chunk";
import { TraceEvent } from "./trace";
import { EvaluationMetrics, ComparisonMetrics } from "./metrics";
import { DocumentDataset } from "./dataset";

export type PipelineId = "advanced-rag" | "laya-rag";

export type PipelineExecutionStatus = "idle" | "running" | "completed" | "failed";

/**
 * Result of executing an individual RAG pipeline path
 */
export interface PipelineResult {
  /** Pipeline identifier */
  pipelineId: PipelineId;

  /** Human-readable strategy name (e.g. "Cross-Encoder Reranker" or "Laya Relevance Filter") */
  strategyName: string;

  /** Execution status */
  status: PipelineExecutionStatus;

  /** Final natural language answer generated by downstream LLM */
  answer?: string;

  /** Time spent in bi-encoder / vector candidate retrieval (ms) */
  retrievalLatencyMs?: number;

  /** Time spent in post-retrieval relevance evaluation/filtering (ms) */
  relevanceEvaluationLatencyMs?: number;

  /** Time spent in downstream LLM generation (ms) */
  generationLatencyMs?: number;

  /** End-to-end execution latency (ms) */
  totalLatencyMs?: number;

  /** Prompt tokens passed to generator */
  inputTokens?: number;

  /** Output tokens generated by model */
  outputTokens?: number;

  /** Total tokens consumed */
  totalTokens?: number;

  /** Number of candidate chunks retrieved originally */
  candidateChunkCount?: number;

  /** Number of chunks retained after relevance evaluation */
  retainedChunkCount?: number;

  /** Number of chunks filtered out */
  discardedChunkCount?: number;

  /** Chunks selected for prompt context */
  retainedChunks?: Chunk[];

  /** Chunks discarded during relevance filtering */
  discardedChunks?: Chunk[];

  /** Sequence of decision trace events recorded by observer */
  trace?: TraceEvent[];

  /** Quality and efficiency metrics */
  metrics?: EvaluationMetrics;

  /** Error details if pipeline execution encountered an exception */
  error?: string;
}

/**
 * Experiment Model
 * Represents a single evaluation run comparing both pipelines for the SAME query and document set.
 */
export interface Experiment {
  /** Unique experiment run identifier */
  id: string;

  /** Natural language query evaluated */
  query: string;

  /** Target document set / dataset collection */
  dataset: DocumentDataset;

  /** Epoch millisecond timestamp of the experiment */
  timestamp: number;

  /** Execution status of the benchmark run */
  status: PipelineExecutionStatus;

  /** Path A result: Advanced RAG with Cross-Encoder Reranker */
  advancedRagResult?: PipelineResult;

  /** Path B result: Laya RAG with Laya Relevance Evaluator */
  layaResult?: PipelineResult;

  /** Comparative delta metrics and summary */
  comparison?: ComparisonMetrics;
}
